"""
sync_s3_assets.py
==================
Utility to incrementally synchronize 3D assets, metadata, and scripts between
local disk and Amazon S3. Files are content-hashed and unchanged files are
skipped by default.

Usage:
  # Upload local assets to S3
  python sync_s3_assets.py --direction upload --bucket my-archigen-storage

  # Download remote assets from S3 to local folder
  python sync_s3_assets.py --direction download --bucket my-archigen-storage

  # Dry run (list files without transferring)
  python sync_s3_assets.py --direction upload --dry-run

  # Transfer everything, even when content is unchanged
  python sync_s3_assets.py --direction upload --force
"""

import os
import sys
import argparse
import hashlib
import math
from typing import Optional

try:
    import boto3
    from botocore.exceptions import ClientError, NoCredentialsError
except ImportError:
    boto3 = None


# Files that must travel together for the cloud Blender worker to start and
# generate a house. Paths are relative to ``blender/`` on disk and to the
# configured S3 asset prefix in the bucket.
RUNTIME_BUNDLE = (
    ("scripts/generate_house.py", "scripts/generate_house.py"),
    ("scripts/generate_house_runtime.py", "scripts/generate_house_runtime.py"),
    ("scripts/generate_house_materials.py", "scripts/generate_house_materials.py"),
    ("scripts/generate_house_structure.py", "scripts/generate_house_structure.py"),
    ("scripts/generate_house_opening_models.py", "scripts/generate_house_opening_models.py"),
    ("scripts/generate_house_openings.py", "scripts/generate_house_openings.py"),
    ("scripts/generate_house_vertical.py", "scripts/generate_house_vertical.py"),
    ("scripts/generate_house_validation.py", "scripts/generate_house_validation.py"),
    ("scripts/import_asset.py", "scripts/import_asset.py"),
    ("scripts/place_furniture.py", "scripts/place_furniture.py"),
    ("scripts/export_glb.py", "scripts/export_glb.py"),
    ("scripts/sync_s3_assets.py", "scripts/sync_s3_assets.py"),
    ("worker_server.py", "worker_server.py"),
    (
        "assets/furniture/bedroom/wardrobes/wardrobe_modern_01.glb",
        "furniture/bedroom/wardrobes/wardrobe_modern_01.glb",
    ),
    ("metadata/wardrobe_modern_01.json", "metadata/wardrobe_modern_01.json"),
)


def _missing_local_runtime_files(blender_dir: str) -> list[str]:
    """Return required runtime paths that are absent from the local bundle."""
    return [
        local_rel
        for local_rel, _ in RUNTIME_BUNDLE
        if not os.path.isfile(os.path.join(blender_dir, *local_rel.split("/")))
    ]


def _load_env():
    """Attempts to load AWS credentials from backend/gem_api.env if present."""
    script_dir = os.path.dirname(os.path.abspath(__file__))
    possible_paths = [
        os.path.join(script_dir, "..", "..", "backend", "gem_api.env"),
        os.path.join(script_dir, "..", "gem_api.env"),
    ]
    for p in possible_paths:
        if os.path.isfile(p):
            with open(p, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith("#") and "=" in line:
                        k, v = line.split("=", 1)
                        k, v = k.strip(), v.strip().strip('"').strip("'")
                        if k and v and k not in os.environ:
                            os.environ[k] = v
            break


_load_env()


def get_s3_client(
    aws_access_key: Optional[str] = None,
    aws_secret_key: Optional[str] = None,
    region: Optional[str] = None
):
    """Initializes and returns a boto3 S3 client."""
    if boto3 is None:
        raise ImportError("boto3 is not installed. Please run 'pip install boto3'.")

    return boto3.client(
        "s3",
        aws_access_key_id=aws_access_key or os.getenv("AWS_ACCESS_KEY_ID"),
        aws_secret_access_key=aws_secret_key or os.getenv("AWS_SECRET_ACCESS_KEY"),
        region_name=region or os.getenv("AWS_REGION", "us-east-1")
    )


def _file_digest(path: str, algorithm: str = "sha256") -> str:
    digest = hashlib.new(algorithm)
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _multipart_etag(path: str, part_size: int) -> str:
    """Reproduce the ETag generated by a standard multipart S3 upload."""
    part_digests = []
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(part_size), b""):
            part_digests.append(hashlib.md5(chunk).digest())
    if len(part_digests) <= 1:
        return part_digests[0].hex() if part_digests else hashlib.md5(b"").hexdigest()
    combined = hashlib.md5(b"".join(part_digests)).hexdigest()
    return f"{combined}-{len(part_digests)}"


def _head_object(s3_client, bucket_name: str, s3_key: str):
    try:
        return s3_client.head_object(Bucket=bucket_name, Key=s3_key)
    except ClientError as err:
        code = str(err.response.get("Error", {}).get("Code", ""))
        if code in {"404", "NoSuchKey", "NotFound"}:
            return None
        raise


def _local_matches_remote(local_path: str, remote_head: Optional[dict]) -> bool:
    """Compare content hashes; size alone is never treated as proof of equality."""
    if not remote_head or not os.path.isfile(local_path):
        return False
    if int(remote_head.get("ContentLength", -1)) != os.path.getsize(local_path):
        return False
    remote_sha256 = str(remote_head.get("Metadata", {}).get("sha256", ""))
    if remote_sha256:
        return remote_sha256 == _file_digest(local_path, "sha256")
    etag = str(remote_head.get("ETag", "")).strip('"')
    if not etag:
        return False
    if "-" not in etag:
        return etag == _file_digest(local_path, "md5")
    # Older assets were uploaded by boto3 without sha256 metadata. Boto3's
    # default multipart chunk is 8 MiB; common larger chunks are accepted for
    # compatibility with earlier AWS CLI uploads.
    try:
        expected_parts = int(etag.rsplit("-", 1)[1])
    except (ValueError, IndexError):
        return False
    for part_size in (8, 16, 32, 64, 128):
        size_bytes = part_size * 1024 * 1024
        if math.ceil(os.path.getsize(local_path) / size_bytes) != expected_parts:
            continue
        if _multipart_etag(local_path, size_bytes) == etag:
            return True
    return False


def upload_assets(
    blender_dir: str,
    bucket_name: str,
    s3_prefix: str = "assets/",
    dry_run: bool = False,
    s3_client=None,
    force: bool = False,
) -> tuple[int, int, int]:
    """
    Uploads local furniture, doors, windows, textures, metadata, and scripts to S3.
    Target directories:
      - blender/assets/furniture/ -> s3://bucket/assets/furniture/
      - blender/assets/doors/     -> s3://bucket/assets/doors/
      - blender/assets/windows/   -> s3://bucket/assets/windows/
      - blender/assets/textures/  -> s3://bucket/assets/textures/
      - blender/metadata/         -> s3://bucket/assets/metadata/
      - blender/scripts/          -> s3://bucket/assets/scripts/
      - blender/worker_server.py  -> s3://bucket/assets/worker_server.py
    """
    if s3_client is None:
        s3_client = get_s3_client()

    missing_runtime = _missing_local_runtime_files(blender_dir)
    if missing_runtime:
        print("[ERROR] Runtime bundle is incomplete; upload cancelled.")
        for relative_path in missing_runtime:
            print(f"[ERROR] Missing required file: blender/{relative_path}")
        return 0, 0, len(missing_runtime)

    print(f"[BUNDLE] Verified {len(RUNTIME_BUNDLE)} required runtime files locally.")

    upload_count = 0
    unchanged_count = 0
    failed_count = 0
    folders_to_upload = [
        (os.path.join(blender_dir, "assets", "architecture"), f"{s3_prefix}architecture/"),
        (os.path.join(blender_dir, "assets", "furniture"), f"{s3_prefix}furniture/"),
        (os.path.join(blender_dir, "assets", "doors"), f"{s3_prefix}doors/"),
        (os.path.join(blender_dir, "assets", "windows"), f"{s3_prefix}windows/"),
        (os.path.join(blender_dir, "assets", "textures"), f"{s3_prefix}textures/"),
        (os.path.join(blender_dir, "metadata"), f"{s3_prefix}metadata/"),
        (os.path.join(blender_dir, "scripts"), f"{s3_prefix}scripts/"),
    ]

    for local_folder, remote_prefix in folders_to_upload:
        if not os.path.exists(local_folder):
            print(f"[WARN] Local directory does not exist: {local_folder}")
            continue

        for root, _, files in os.walk(local_folder):
            for file in files:
                if file == ".gitkeep" or file.endswith(".tmp") or file.endswith(".pyc") or "__pycache__" in root:
                    continue

                abs_path = os.path.join(root, file)
                rel_path = os.path.relpath(abs_path, local_folder).replace("\\", "/")
                s3_key = f"{remote_prefix}{rel_path}"

                content_type = (
                    "model/gltf-binary" if file.endswith(".glb") else
                    "model/gltf+json" if file.endswith(".gltf") else
                    "image/jpeg" if file.lower().endswith((".jpg", ".jpeg")) else
                    "image/png" if file.lower().endswith(".png") else
                    "application/json" if file.endswith(".json") else
                    "text/x-python" if file.endswith(".py") else
                    "application/octet-stream"
                )

                try:
                    remote_head = None if force else _head_object(s3_client, bucket_name, s3_key)
                    if not force and _local_matches_remote(abs_path, remote_head):
                        unchanged_count += 1
                        print(f"[SKIP] unchanged: {s3_key}")
                        continue

                    print(f"[{'WOULD UPLOAD' if dry_run else 'UPLOAD'}] {abs_path} -> s3://{bucket_name}/{s3_key}")
                    if not dry_run:
                        sha256 = _file_digest(abs_path, "sha256")
                        s3_client.upload_file(
                            abs_path,
                            bucket_name,
                            s3_key,
                            ExtraArgs={
                                "ContentType": content_type,
                                "CacheControl": "no-cache",
                                "Metadata": {"sha256": sha256},
                            }
                        )
                    upload_count += 1
                except (ClientError, NoCredentialsError, OSError) as err:
                    failed_count += 1
                    print(f"[ERROR] Failed to upload {file}: {err}")

    worker_server_path = os.path.join(blender_dir, "worker_server.py")
    worker_server_key = f"{s3_prefix}worker_server.py"
    if os.path.isfile(worker_server_path):
        try:
            remote_head = (
                None
                if force
                else _head_object(s3_client, bucket_name, worker_server_key)
            )
            if not force and _local_matches_remote(worker_server_path, remote_head):
                unchanged_count += 1
                print(f"[SKIP] unchanged: {worker_server_key}")
            else:
                action = "WOULD UPLOAD" if dry_run else "UPLOAD"
                print(
                    f"[{action}] {worker_server_path} -> "
                    f"s3://{bucket_name}/{worker_server_key}"
                )
                if not dry_run:
                    sha256 = _file_digest(worker_server_path, "sha256")
                    s3_client.upload_file(
                        worker_server_path,
                        bucket_name,
                        worker_server_key,
                        ExtraArgs={
                            "ContentType": "text/x-python",
                            "CacheControl": "no-cache",
                            "Metadata": {"sha256": sha256},
                        },
                    )
                upload_count += 1
        except (ClientError, NoCredentialsError, OSError) as err:
            failed_count += 1
            print(f"[ERROR] Failed to upload worker_server.py: {err}")

    return upload_count, unchanged_count, failed_count


def download_assets(
    blender_dir: str,
    bucket_name: str,
    s3_prefix: str = "assets/",
    dry_run: bool = False,
    s3_client=None,
    force: bool = False,
) -> tuple[int, int, int]:
    """
    Downloads remote assets from S3 to local blender directories.
    """
    if s3_client is None:
        s3_client = get_s3_client()

    download_count = 0
    unchanged_count = 0
    failed_count = 0
    remote_runtime_files = set()
    try:
        paginator = s3_client.get_paginator("list_objects_v2")
        pages = paginator.paginate(Bucket=bucket_name, Prefix=s3_prefix)

        for page in pages:
            for obj in page.get("Contents", []):
                s3_key = obj["Key"]
                if s3_key.endswith("/"):
                    continue

                rel_key = s3_key[len(s3_prefix):]
                remote_runtime_files.add(rel_key)
                if rel_key == "worker_server.py":
                    local_path = os.path.join(blender_dir, "worker_server.py")
                elif rel_key.startswith("metadata/"):
                    local_path = os.path.join(blender_dir, rel_key)
                elif rel_key.startswith("furniture/"):
                    local_path = os.path.join(blender_dir, "assets", rel_key)
                elif rel_key.startswith("scripts/"):
                    local_path = os.path.join(blender_dir, rel_key)
                else:
                    local_path = os.path.join(blender_dir, "assets", rel_key)

                try:
                    remote_head = None if force else _head_object(s3_client, bucket_name, s3_key)
                    if not force and _local_matches_remote(local_path, remote_head):
                        unchanged_count += 1
                        print(f"[SKIP] unchanged: {s3_key}")
                        continue
                    os.makedirs(os.path.dirname(local_path), exist_ok=True)
                    print(f"[{'WOULD DOWNLOAD' if dry_run else 'DOWNLOAD'}] s3://{bucket_name}/{s3_key} -> {local_path}")
                    if not dry_run:
                        s3_client.download_file(bucket_name, s3_key, local_path)
                    download_count += 1
                except (ClientError, NoCredentialsError, OSError) as err:
                    failed_count += 1
                    print(f"[ERROR] Failed to download {s3_key}: {err}")

    except (ClientError, NoCredentialsError) as err:
        print(f"[ERROR] S3 operation failed: {err}")
        failed_count += 1

    missing_remote = [
        remote_rel
        for _, remote_rel in RUNTIME_BUNDLE
        if remote_rel not in remote_runtime_files
    ]
    if missing_remote:
        print("[ERROR] S3 runtime bundle is incomplete.")
        for relative_path in missing_remote:
            print(f"[ERROR] Missing required S3 object: {s3_prefix}{relative_path}")
        failed_count += len(missing_remote)
    elif not dry_run:
        missing_local = _missing_local_runtime_files(blender_dir)
        if missing_local:
            print("[ERROR] Runtime bundle download did not create every local file.")
            for relative_path in missing_local:
                print(f"[ERROR] Missing after download: blender/{relative_path}")
            failed_count += len(missing_local)
        else:
            print(f"[BUNDLE] Verified {len(RUNTIME_BUNDLE)} required runtime files after download.")

    return download_count, unchanged_count, failed_count


def main():
    parser = argparse.ArgumentParser(description="Sync 3D assets with AWS S3.")
    parser.add_argument(
        "--direction",
        choices=["upload", "download"],
        default="upload",
        help="Transfer direction: upload local assets to S3, or download from S3."
    )
    parser.add_argument(
        "--bucket",
        default=os.getenv("AWS_S3_BUCKET", "archigen-storage"),
        help="Target AWS S3 bucket name."
    )
    parser.add_argument(
        "--prefix",
        default="assets/",
        help="S3 Key prefix (default: assets/)."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Perform dry run without uploading or downloading files."
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Transfer every file without checking whether its content changed."
    )
    args = parser.parse_args()

    script_dir = os.path.dirname(os.path.abspath(__file__))
    blender_dir = os.path.dirname(script_dir)

    print(f"=== ArchGen S3 Asset Sync ===")
    print(f"Mode: {args.direction.upper()} {'(DRY RUN)' if args.dry_run else ''}")
    print(f"Bucket: {args.bucket}")
    print(f"Blender Directory: {blender_dir}")

    if boto3 is None:
        print("[ERROR] boto3 is required. Run: pip install boto3")
        sys.exit(1)

    try:
        s3 = get_s3_client()
    except Exception as err:
        print(f"[WARN] S3 Client initialization warning: {err}")
        s3 = None

    if args.direction == "upload":
        changed, unchanged, failed = upload_assets(
            blender_dir,
            args.bucket,
            args.prefix,
            dry_run=args.dry_run,
            s3_client=s3,
            force=args.force,
        )
        action = "would upload" if args.dry_run else "uploaded"
    else:
        changed, unchanged, failed = download_assets(
            blender_dir,
            args.bucket,
            args.prefix,
            dry_run=args.dry_run,
            s3_client=s3,
            force=args.force,
        )
        action = "would download" if args.dry_run else "downloaded"
    print(f"Finished. Files {action}: {changed}; unchanged: {unchanged}; failed: {failed}")
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
